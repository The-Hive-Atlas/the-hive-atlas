"""Pull sample sizes and response rates out of the NASS Honey Bee Colonies quality reports.

NASS publishes a "Methodology and Quality Measures" report each year, covering the two
previous survey years. Get them from:
https://www.nass.usda.gov/Publications/Methodology_and_Data_Quality/Honey_Bee_Colonies/index.php

Usage:
    for f in hbclqm21 hbclqm22 hblqm23 hblqm24 hblqm25 hblqm26; do pdftotext -layout $f.pdf $f.txt; done
    python3 pipeline/build_quality.py data/colony-quality.js data/nass-quality.csv hbclqm21.txt hbclqm22.txt ...

Each table is "Quality Metrics for Quarterly Colony Loss Survey - States and United States:
<Month> 1, <year1> and <Month> 1, <year2>" with, for each year: sample size, response rate,
weighted item response rate, and coefficient of variation. All four describe the first-of-quarter
colony inventory estimate (not the loss rate).

Years appear in two reports; the newer report wins, since NASS revises earlier figures.
"""
import csv
import json
import re
import sys

MONTH_Q = {'January': 1, 'April': 2, 'July': 3, 'October': 4}
NAMES = {
    'Alabama': 'AL', 'Alaska': 'AK', 'Arizona': 'AZ', 'Arkansas': 'AR', 'California': 'CA', 'Colorado': 'CO',
    'Connecticut': 'CT', 'Delaware': 'DE', 'Florida': 'FL', 'Georgia': 'GA', 'Hawaii': 'HI', 'Idaho': 'ID',
    'Illinois': 'IL', 'Indiana': 'IN', 'Iowa': 'IA', 'Kansas': 'KS', 'Kentucky': 'KY', 'Louisiana': 'LA',
    'Maine': 'ME', 'Maryland': 'MD', 'Massachusetts': 'MA', 'Michigan': 'MI', 'Minnesota': 'MN',
    'Mississippi': 'MS', 'Missouri': 'MO', 'Montana': 'MT', 'Nebraska': 'NE', 'Nevada': 'NV',
    'New Hampshire': 'NH', 'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC',
    'North Dakota': 'ND', 'Ohio': 'OH', 'Oklahoma': 'OK', 'Oregon': 'OR', 'Pennsylvania': 'PA',
    'Rhode Island': 'RI', 'South Carolina': 'SC', 'South Dakota': 'SD', 'Tennessee': 'TN', 'Texas': 'TX',
    'Utah': 'UT', 'Vermont': 'VT', 'Virginia': 'VA', 'Washington': 'WA', 'West Virginia': 'WV',
    'Wisconsin': 'WI', 'Wyoming': 'WY', 'Other States': 'OTH', 'United States': 'US',
}
TITLE = re.compile(r'Quality Metrics for Quarterly Colony Loss Survey - States and United States:\s*(\w+) 1, (\d{4}) and')
ROW = re.compile(r'^([A-Z][A-Za-z ]+?)\s*\d?\s*\.{2,}\s*(.+)$')
TOKEN = re.compile(r'\(NA\)|\(D\)|\(Z\)|-|[\d,]+(?:\.\d+)?')


def num(t):
    if t in ('(NA)', '(D)', '(Z)'):
        return None
    if t == '-':
        return 0
    return float(t.replace(',', ''))


def parse(path):
    """Yield (year, quarter, code, sample, response, weighted, cv) from one report."""
    lines = open(path, encoding='utf-8', errors='replace').read().splitlines()
    cur = None
    for line in lines:
        m = TITLE.search(line)
        if m:
            cur = (MONTH_Q[m.group(1)], int(m.group(2)))
            continue
        if not cur:
            continue
        r = ROW.match(line.strip())
        if not r:
            continue
        name = r.group(1).strip()
        if name not in NAMES:
            continue
        toks = TOKEN.findall(r.group(2))
        if len(toks) != 8:
            raise ValueError('%s: expected 8 values for %s, got %d: %r' % (path, name, len(toks), line))
        q, y1 = cur
        vals = [num(t) for t in toks]
        # columns: sample y1, y2 | response y1, y2 | weighted y1, y2 | cv y1, y2
        for i, y in enumerate((y1, y1 + 1)):
            yield (y, q, NAMES[name], vals[0 + i], vals[2 + i], vals[4 + i], vals[6 + i])


def main(out_js, out_csv, *reports):
    data, seen, revised = {}, {}, 0
    # newest report last, so it overwrites older figures for the same year
    for path in sorted(reports, key=lambda p: re.search(r'(\d\d)\.txt$', p).group(1)):
        for y, q, code, s, r, w, cv in parse(path):
            pid = '%d-Q%d' % (y, q)
            key = (pid, code)
            row = [s, r, w, cv]
            if all(v is None for v in row):
                continue
            if key in seen and seen[key] != row:
                revised += 1
            seen[key] = row
            data.setdefault(pid, {})[code] = row
    with open(out_csv, 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['period', 'state_abbr', 'sample_size', 'response_rate_pct', 'weighted_item_response_rate_pct', 'cv_pct_inventory'])
        for pid in sorted(data):
            for code in sorted(data[pid]):
                w.writerow([pid, code] + ['' if v is None else (int(v) if i == 0 else v) for i, v in enumerate(data[pid][code])])
    with open(out_js, 'w') as f:
        f.write('/* NASS Honey Bee Colonies quality metrics: [sample size, response rate %, weighted item response rate %, CV % of first-of-quarter inventory].\n'
                '   Generated by pipeline/build_quality.py from the NASS Methodology and Quality Measures reports. */\n')
        f.write('window.HIVE_QUALITY = ')
        json.dump({'fields': ['sample', 'response', 'weighted', 'cv'], 'periods': data}, f, separators=(',', ':'))
        f.write(';\n')
    print('%d quarters, %d state-quarter rows, %d values revised by a newer report' %
          (len(data), sum(len(v) for v in data.values()), revised))


if __name__ == '__main__':
    main(*sys.argv[1:])
