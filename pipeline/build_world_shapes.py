#!/usr/bin/env python3
"""Build the world outline used by the "Worldwide" view of the Genetic Diversity map.

Usage:
    python3 pipeline/build_world_shapes.py ne_50m_admin_0_countries.geojson data/genetics.js data/world-shapes.js

ne_50m_admin_0_countries.geojson is Natural Earth's 1:50m countries file (public domain), from
https://github.com/nvkelso/natural-earth-vector (geojson folder). Run it after build_genetics.py.

Writes every country (Antarctica left out) as simplified longitude/latitude rings, plus which
spreadsheet country each sampled outline belongs to:
  window.HIVE_WORLD_SHAPES = { "land": [[ring...], ...] for unsampled countries,
                               "sampled": { "<country key>": [[ring...], ...] } }
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_country_shapes import simplify, area  # noqa: E402

TOLERANCE = 0.15   # degrees
MIN_AREA = 0.3     # square degrees; smaller islands of unsampled countries are dropped
PAD = 6            # degrees; a sampled country's land parts this close to a sampled area are colored


def rings_of(geom, tol, min_area):
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    out = []
    for pl in polys:
        if area(pl[0]) < min_area:
            continue
        rings = []
        for r in pl:
            s = simplify([[round(x, 3), round(y, 3)] for x, y in r], tol)
            if len(s) >= 4:
                rings.append([[round(x, 1), round(y, 1)] for x, y in s])
        if rings:
            out.append(rings)
    return out


def main(ne_file, genetics_js, out_js):
    ne = json.loads(Path(ne_file).read_text(encoding="utf-8"))
    text = Path(genetics_js).read_text(encoding="utf-8")
    G = json.loads(text[text.index("{"):text.rindex("}") + 1])
    owner = {}
    for c in G["countries"]:
        for iso in c["iso"]:
            owner[iso] = c["key"]
    areas_of = {c["key"]: [(a["lon"], a["lat"]) for a in c["areas"] if a["lat"] is not None] for c in G["countries"]}
    land, sampled = [], {}
    for f in ne["features"]:
        p = f["properties"]
        if p.get("ADM0_A3") in ("ATA", "CLP"):
            continue
        key = owner.get(p.get("ISO_N3_EH"))
        if key:
            # Only the parts of a sampled country near its sampled areas get colored (so French Guiana
            # is not colored for samples from mainland France); the rest is drawn as plain land.
            pts = areas_of[key]
            for pl in rings_of(f["geometry"], TOLERANCE / 2, 0.002):
                xs = [q[0] for q in pl[0]]; ys = [q[1] for q in pl[0]]
                near = not pts or any(min(xs) - PAD <= x <= max(xs) + PAD and min(ys) - PAD <= y <= max(ys) + PAD for x, y in pts)
                (sampled.setdefault(key, []) if near else land).append(pl)
        else:
            land.extend(rings_of(f["geometry"], TOLERANCE, MIN_AREA))
    missing = [c["name"] for c in G["countries"] if c["key"] not in sampled]
    if missing:
        print("WARNING: no world outline for", ", ".join(missing))
    out = {"land": land, "sampled": sampled}
    Path(out_js).write_text(
        "/* The Hive Atlas: world outline for the Genetic Diversity map (Worldwide view). Natural Earth 1:50m "
        "(public domain), simplified. Generated by pipeline/build_world_shapes.py. Rings of [longitude, latitude]. */\n"
        "window.HIVE_WORLD_SHAPES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print("Wrote %s (%d KB): %d other land parts, %d sampled countries" % (
        out_js, Path(out_js).stat().st_size // 1024, len(land), len(sampled)))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
