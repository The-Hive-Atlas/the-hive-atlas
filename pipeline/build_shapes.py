"""Turn the us-atlas state boundaries into SVG paths for the Hive Atlas maps.

Run once (the boundaries rarely change):
    npm pack us-atlas@3.0.1 && tar xzf us-atlas-3.0.1.tgz
    python3 pipeline/build_shapes.py package/states-albers-10m.json data/state-shapes.js

The input is already projected (Albers USA, with Alaska and Hawaii as insets)
into a 975 x 610 box, so the paths can be drawn directly in an SVG.
Source boundaries: U.S. Census Bureau cartographic boundary files, via us-atlas.
"""
import json
import sys

FIPS = {
    '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE',
    '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA',
    '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN',
    '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM',
    '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI',
    '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA',
    '54': 'WV', '55': 'WI', '56': 'WY',
}


def decode_arcs(topo):
    tr = topo.get('transform')
    arcs = []
    for arc in topo['arcs']:
        x = y = 0
        pts = []
        for p in arc:
            if tr:
                x += p[0]
                y += p[1]
                pts.append((x * tr['scale'][0] + tr['translate'][0], y * tr['scale'][1] + tr['translate'][1]))
            else:
                pts.append((p[0], p[1]))
        arcs.append(pts)
    return arcs


def ring_points(ring, arcs):
    out = []
    for i in ring:
        pts = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        out.extend(pts if not out else pts[1:])
    return out


def ring_path(pts):
    s = []
    last = None
    for x, y in pts:
        p = (round(x, 1), round(y, 1))
        if p == last:
            continue
        s.append('%g,%g' % p)
        last = p
    return 'M' + 'L'.join(s) + 'Z'


def main(src, dst):
    topo = json.load(open(src))
    arcs = decode_arcs(topo)
    shapes = {}
    for g in topo['objects']['states']['geometries']:
        code = FIPS.get(str(g['id']).zfill(2))
        if not code:
            continue
        polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
        shapes[code] = ''.join(ring_path(ring_points(r, arcs)) for poly in polys for r in poly)
    with open(dst, 'w') as f:
        f.write('/* State outlines for The Hive Atlas maps. Generated by pipeline/build_shapes.py from us-atlas 3.0.1 (U.S. Census Bureau boundaries). */\n')
        f.write('window.HIVE_SHAPES = {"viewBox":[0,0,975,610],"states":')
        json.dump(shapes, f, separators=(',', ':'))
        f.write('};\n')
    print('wrote %d states to %s' % (len(shapes), dst))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
