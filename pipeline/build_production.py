"""Turn the cleaned NASS honey CSV into the data file the Honey Production map reads.

Usage:
    python3 pipeline/clean_nass_honey.py QUICKSTATS_EXPORT.csv data/nass-honey-production.csv REVIEW.xlsx
    python3 pipeline/build_production.py data/nass-honey-production.csv data/honey-production.js 2026-03-20

The last argument is the release date of the latest NASS Honey report (optional).

Output: a JavaScript file defining window.HIVE_HONEY. A script file is used instead of JSON so the
page also works when opened straight from your computer.
"""
import csv
import json
import sys
from datetime import date

FIELDS = ['colonies', 'yield_lb', 'production_lb', 'stocks_lb', 'price_usd_lb', 'value_usd', 'price_usd_lb_real', 'value_usd_real']

NAMES = {
    'AL': 'Alabama', 'AK': 'Alaska', 'AZ': 'Arizona', 'AR': 'Arkansas', 'CA': 'California', 'CO': 'Colorado',
    'CT': 'Connecticut', 'DE': 'Delaware', 'DC': 'District of Columbia', 'FL': 'Florida', 'GA': 'Georgia',
    'HI': 'Hawaii', 'ID': 'Idaho', 'IL': 'Illinois', 'IN': 'Indiana', 'IA': 'Iowa', 'KS': 'Kansas',
    'KY': 'Kentucky', 'LA': 'Louisiana', 'ME': 'Maine', 'MD': 'Maryland', 'MA': 'Massachusetts',
    'MI': 'Michigan', 'MN': 'Minnesota', 'MS': 'Mississippi', 'MO': 'Missouri', 'MT': 'Montana',
    'NE': 'Nebraska', 'NV': 'Nevada', 'NH': 'New Hampshire', 'NJ': 'New Jersey', 'NM': 'New Mexico',
    'NY': 'New York', 'NC': 'North Carolina', 'ND': 'North Dakota', 'OH': 'Ohio', 'OK': 'Oklahoma',
    'OR': 'Oregon', 'PA': 'Pennsylvania', 'RI': 'Rhode Island', 'SC': 'South Carolina',
    'SD': 'South Dakota', 'TN': 'Tennessee', 'TX': 'Texas', 'UT': 'Utah', 'VT': 'Vermont',
    'VA': 'Virginia', 'WA': 'Washington', 'WV': 'West Virginia', 'WI': 'Wisconsin', 'WY': 'Wyoming',
    'US': 'United States', 'OTH': 'Other States',
}


def num(v):
    v = (v or '').strip()
    if v == '':
        return None
    f = float(v)
    return int(f) if f.is_integer() else f


def main(src, dst, release=''):
    rows = list(csv.DictReader(open(src, newline='', encoding='utf-8')))
    values, years, cpi_base = {}, set(), None
    for r in rows:
        y = int(r['year'])
        years.add(y)
        values.setdefault(r['state_abbr'], {})[str(y)] = [num(r[f]) for f in FIELDS]
        cpi_base = r['cpi_base']
    years = sorted(years)
    data = {
        'source': {
            'name': 'USDA National Agricultural Statistics Service, Honey report (via Quick Stats)',
            'url': 'https://esmis.nal.usda.gov/publication/honey',
            'release': release,
            'built': date.today().isoformat(),
            'cpiBaseYear': 2025,
            'cpiBase': float(cpi_base),
        },
        'fields': FIELDS,
        'names': NAMES,
        'years': years,
        # Years in which NASS grouped some states into Other States
        'otherYears': sorted(int(y) for y in values.get('OTH', {})),
        'values': values,
    }
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('/* NASS honey production by state and year. Generated by pipeline/build_production.py. */\n')
        f.write('window.HIVE_HONEY = ')
        json.dump(data, f, separators=(',', ':'))
        f.write(';\n')
    print('wrote %d years (%d-%d), %d areas to %s' % (len(years), years[0], years[-1], len(values), dst))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else '')
