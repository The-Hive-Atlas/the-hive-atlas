"""Build the references shown under the Disease Surveillance map.

Usage:
    python3 pipeline/build_disease_refs.py BRL_1984_2026_PUBLISHED_cleaned.xlsx data/disease.js data/disease-refs.js

Run it after pipeline/build_disease_world.py. It reads the Reference and DOI columns of the ADULTS, BROOD and
ANTIBIOTICS sheets, row by row, and counts samples per area, year, month and reference. It counts the same rows as
data/disease.js (rows left out there are left out here) and takes the area numbers from that file.

Output: window.HIVE_DISEASE_REFS = { refs: [{t, doi, kind}], rows: [[area, year, month, ref, samples], ...] }.
A blank Reference has kind "none"; "Unpublished" and "Unpublished Data" are one entry of kind "unpublished"; both kinds are listed on the page.
A row in ANTIBIOTICS counts once, even when it holds both a tetracycline and a tylosin result.
"""
import json
import sys
from collections import Counter
from pathlib import Path

import openpyxl

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_disease import NAMES, MONTHS, FIX_STATE  # noqa: E402
from build_disease_world import COUNTRY, PROVINCES, read_sheet, flag  # noqa: E402

NAMES = dict(NAMES, VI='U.S. Virgin Islands')


def clean_doi(v):
    s = ' '.join(str(v or '').replace('\xa0', ' ').split())
    return s[4:].strip() if s.upper().startswith('DOI:') else s


def key_of(r):
    """Same area, year and month as build_disease_world.py, or None for a row it leaves out."""
    cname = str(r['Country'] or '').strip()
    if cname not in COUNTRY:
        return None
    iso = COUNTRY[cname][0]
    stc = str(r['State'] or '').strip().upper()
    if iso == 'USA':
        stc = FIX_STATE.get(stc, stc)
        if stc not in NAMES or stc == 'US':
            return None
        a = stc
    elif iso == 'CAN':
        a = 'CAN.' + (stc if stc in PROVINCES else '-')
    else:
        a = iso + '.-'
    return a, int(r['Year']), MONTHS.get(str(r['Month'] or '').strip()[:3].title(), 0)


def main(src, site_js, dst):
    text = Path(site_js).read_text(encoding='utf-8')
    data = json.loads(text[text.index('{'):text.rindex('}') + 1])
    aidx = {a: i for i, a in enumerate(data['areas'])}
    wb = openpyxl.load_workbook(src, read_only=True)
    refs, ids, cube = [], {}, Counter()

    def add(r):
        k = key_of(r)
        if not k:
            return
        t = ' '.join(str(r['Reference'] or '').replace('\xa0', ' ').split())
        if t.lower() == 'unpublished':
            t = 'Unpublished Data'
        doi = clean_doi(r['DOI'])
        if (t, doi) not in ids:
            kind = 'none' if not t else 'unpublished' if t.lower() == 'unpublished data' else 'study'
            ids[(t, doi)] = len(refs)
            refs.append({'t': t, 'doi': doi, 'kind': kind})
        cube[(aidx[k[0]], k[1], k[2], ids[(t, doi)])] += 1

    for r in read_sheet(wb['ADULTS']):
        add(r)
    for r in read_sheet(wb['BROOD']):
        if flag(r['AFB']) is not None and flag(r['EFB']) is not None:
            add(r)
    for r in read_sheet(wb['ANTIBIOTICS']):
        if any(isinstance(r[n], (int, float)) and not isinstance(r[n], bool) for n in ('TE_mm', 'TY_mm')):
            add(r)

    rows = [list(k) + [n] for k, n in sorted(cube.items(), key=lambda kv: (kv[0][1], kv[0][0], kv[0][2], kv[0][3]))]
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('/* The Hive Atlas: references cited by the rows of the published BRL workbook, as samples per area, year, month and '
                'reference. Generated by pipeline/build_disease_refs.py. */\nwindow.HIVE_DISEASE_REFS = ')
        json.dump({'refs': refs, 'rows': rows}, f, separators=(',', ':'), ensure_ascii=False)
        f.write(';\n')
    tally = Counter()
    for k, n in cube.items():
        tally[k[3]] += n
    for i, r in enumerate(refs):
        print(tally[i], r['kind'], r['doi'] or '-', r['t'][:80])
    print('wrote', dst, Path(dst).stat().st_size // 1024, 'KB,', len(rows), 'rows')


if __name__ == '__main__':
    main(*sys.argv[1:])
