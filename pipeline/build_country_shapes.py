#!/usr/bin/env python3
"""Build the country outlines used by the Genetic Diversity map for countries other than the U.S.

Usage:
    python3 pipeline/build_country_shapes.py ne_10m_admin_0_countries.geojson data/genetics.js data/country-shapes.js

ne_10m_admin_0_countries.geojson is Natural Earth's 1:10m countries file (public domain), from
https://github.com/nvkelso/natural-earth-vector (geojson folder). Run this after build_genetics.py,
because it reads the country list and area coordinates from data/genetics.js.

For each country it keeps only the land near the sampled areas (so far-off territories such as
French Guiana do not shrink the map), simplifies the outline, and writes longitude/latitude rings:
  window.HIVE_COUNTRY_SHAPES = { "<country key>": [[ring, ring...], ...] }   (rings of [lon, lat])
"""
import json
import math
import sys
from pathlib import Path

PAD = 6          # degrees around the sampled areas; land parts outside this box are dropped
TOLERANCE = 0.02  # degrees; outline simplification (about 2 km)
MIN_AREA = 0.0004  # square degrees; smaller islands are dropped unless they hold a sampled area


def simplify(pts, tol):
    """Douglas-Peucker on a closed ring."""
    if len(pts) < 5:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy) or 1e-12
        best, idx = -1, None
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm if (dx or dy) else math.hypot(px - ax, py - ay)
            if d > best:
                best, idx = d, i
        if idx is not None and best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(ring):
    return abs(sum(ring[i][0] * ring[i - 1][1] - ring[i - 1][0] * ring[i][1] for i in range(len(ring)))) / 2


def bbox(ring):
    xs = [p[0] for p in ring]; ys = [p[1] for p in ring]
    return min(xs), min(ys), max(xs), max(ys)


def main(ne_file, genetics_js, out_js):
    ne = json.loads(Path(ne_file).read_text(encoding="utf-8"))
    text = Path(genetics_js).read_text(encoding="utf-8")
    G = json.loads(text[text.index("{"):text.rindex("}") + 1])
    out = {}
    for c in G["countries"]:
        if c["key"] == "USA":
            continue
        pts = [(a["lon"], a["lat"]) for a in c["areas"] if a["lat"] is not None]
        polys = []
        for f in ne["features"]:
            p = f["properties"]
            if p.get("ISO_N3_EH") not in c["iso"] or p.get("ADM0_A3") == "CLP":
                continue
            g = f["geometry"]
            polys += [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        if pts:
            x0 = min(x for x, _ in pts) - PAD; x1 = max(x for x, _ in pts) + PAD
            y0 = min(y for _, y in pts) - PAD; y1 = max(y for _, y in pts) + PAD
            near = [pl for pl in polys if (lambda b: b[2] >= x0 and b[0] <= x1 and b[3] >= y0 and b[1] <= y1)(bbox(pl[0]))]
            polys = near or polys
        kept = []
        for pl in polys:
            b = bbox(pl[0])
            holds_area = any(b[0] - 0.5 <= x <= b[2] + 0.5 and b[1] - 0.5 <= y <= b[3] + 0.5 for x, y in pts)
            if area(pl[0]) < MIN_AREA and not holds_area:
                continue
            rings = []
            for r in pl:
                s = simplify([[round(x, 3), round(y, 3)] for x, y in r], TOLERANCE)
                if len(s) >= 4:
                    rings.append([[round(x, 2), round(y, 2)] for x, y in s])
            if rings:
                kept.append(rings)
        if not kept:
            print("WARNING: no outline found for %s (ISO %s)" % (c["name"], c["iso"]))
        out[c["key"]] = kept
        print("  %-20s %3d land parts, %5d points" % (c["name"], len(kept), sum(len(r) for pl in kept for r in pl)))
    Path(out_js).write_text(
        "/* The Hive Atlas: country outlines for the Genetic Diversity map. Natural Earth 1:10m (public domain), "
        "simplified. Generated by pipeline/build_country_shapes.py. Rings of [longitude, latitude]. */\n"
        "window.HIVE_COUNTRY_SHAPES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print("Wrote %s (%d KB)" % (out_js, Path(out_js).stat().st_size // 1024))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
